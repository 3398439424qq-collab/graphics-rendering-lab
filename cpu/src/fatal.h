// ── src/fatal.h ─────────────────────────────────────────────
// 提供带调用位置的硬失败诊断；并非项目中唯一的退出路径。
//
// 用途：运行期数值故障或使用方错误（如构造参数非法）时，
//       向 std::cerr 写诊断及换行，然后 std::exit(3) 终止进程；消息含换行时不保证仅一行。
//
// 项目当前退出码约定：
//   2 = CLI 输入非法（参数、尺寸、场景名等）；CLI 侧通过 bad_val() 等路径处理，不由 FATAL 输出
//   3 = FATAL 所用退出码：运行期数值故障或使用方错误（构造参数非法、nullptr 等）
//
// 当前实现选择 std::exit，而非错误返回或异常传播：
//   · 它是失败防线，不是正常控制流；非有限数会污染吞吐量与累加值，
//     并使浮点大小比较难以可靠判定，但并非所有比较都会失效。
//   · 构造参数非法等调用不继续使用无效对象；此项目当前未为这些接口提供恢复路径，
//     不代表构造函数不能通过异常报告失败。
//   · std::exit 不展开当前调用栈，栈上自动对象不会析构；可能跳过资源释放或文件收尾。
//
// 宏用于当前 C++17 实现：让 __FILE__ / __LINE__ 在调用处展开，便于直接记录调用位置。
//   这不是捕获位置的唯一技术方式；这里无需调用方逐次显式传文件名和行号。
//
// 用法：
//   FATAL("world::add called with null object");
//   FATAL("checker_texture: n must be >= 1 (got " << n << ")");   // 多段可直接 << 串起来
//   ⇒ 输出：FATAL: <消息> [src/xxx.h:42]
// ⚠️ msg 按流插入片段展开，不将整串包成 `<< (msg)`：括号会使 "a" << x << "b"
//    先作为独立表达式求值，字符串不能这样左移；保留当前展开才能支持上述多段用法。
// ⚠️ FATAL 是全局预处理宏名：namespace 不限制其作用域，应避免同名冲突。
#pragma once
#include <cstdlib>     // std::exit
#include <iostream>    // std::cerr

#define FATAL(msg)                                                          \
    do {                                                                    \
        std::cerr << "FATAL: " << msg                                       \
                  << " [" << __FILE__ << ":" << __LINE__ << "]\n";          \
        std::exit(3);                                                       \
    } while (0)
